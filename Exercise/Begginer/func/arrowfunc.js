// How to remember arrow functions:
// 1. ( ) → Input box
// 2. =>  → Arrow means "take input and return something"
// 3. Right side → The output you want

// In plain words: 
// "Take input → shoot arrow → give output"

// Examples:
const square = (n) => n * n;         // takes n → arrow → return n*n
const add = (a, b) => a + b;         // takes a, b → arrow → return sum
const greet = (name) => `Hi, ${name}!`; // takes name → arrow → return greeting

